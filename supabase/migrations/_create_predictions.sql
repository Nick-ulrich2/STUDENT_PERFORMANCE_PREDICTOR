-- Student Performance Predictor: prediction snapshots.

create table if not exists public.predictions (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    model_version_id bigint not null references public.model_versions(id),
    attendance double precision not null,
    hours_studied double precision not null,
    previous_scores double precision not null,
    tutoring_sessions integer not null,
    access_to_resources text not null,
    parental_involvement text not null,
    predicted_score decimal(5, 2) not null check (predicted_score between 0 and 100),
    below_threshold json,
    created_at timestamptz default now()
);

create index if not exists predictions_created_at_idx
on public.predictions (created_at);

create index if not exists predictions_model_version_id_idx
on public.predictions (model_version_id);

alter table public.predictions enable row level security;